package com.spacesim.components;

import com.badlogic.ashley.core.Component;
import com.badlogic.gdx.math.Vector2;

/**
 * Пространственное состояние ECS-сущности в двумерном игровом мире.
 *
 * <p>Позицию станций читают рыночная и потребительская системы при проверке
 * радиуса экономических событий. {@link com.spacesim.systems.TradeAISystem}
 * читает позиции станций и напрямую изменяет позицию флота во время перелёта;
 * интерфейс отображает текущие координаты. Оба вектора должны оставаться
 * ненулевыми ссылками.</p>
 */
public class TransformComponent implements Component {
    /**
     * Текущая позиция в единицах координат мира.
     * Начальное значение — начало координат {@code (0, 0)}.
     */
    public Vector2 position = new Vector2();

    /**
     * Вектор скорости в единицах координат мира в секунду.
     * Поле зарезервировано для систем движения; текущий торговый ИИ перемещает
     * {@link #position} непосредственно и не синхронизирует это значение.
     */
    public Vector2 velocity = new Vector2();

    /** Создаёт пространственное состояние с нулевой позицией и скоростью. */
    public TransformComponent() {
    }
}
