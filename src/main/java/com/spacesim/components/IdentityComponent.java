package com.spacesim.components;

import com.badlogic.ashley.core.Component;

/**
 * Неизменяемая пользовательская идентичность отображаемого космического объекта.
 *
 * <p>Компонент отделяет понятное человеку имя и тип объекта от его технической ECS-сущности.
 * Визуальный слой может использовать эти данные для подписей на карте и карточки выбранного
 * объекта, не определяя тип по косвенным признакам вроде наличия рынка, торгового ИИ или запаса
 * астероида.</p>
 *
 * <p>Имя очищается от пробельных символов по краям и после очистки обязано содержать хотя бы
 * один непробельный символ. Тип обязателен. Оба значения неизменяемы в течение жизни компонента:
 * для переименования или преобразования объекта следует заменить компонент целиком.</p>
 */
public final class IdentityComponent implements Component {
    /** Категория космического объекта, определяющая его представление в интерфейсе. */
    public enum Kind {
        /** Неподвижная экономическая станция или другой стационарный объект. */
        STATION,

        /** Подвижный флот либо отдельный корабль, представленный одной ECS-сущностью. */
        FLEET,

        /** Ограниченный природный источник ресурса, который исчезает после истощения. */
        ASTEROID
    }

    /** Отображаемое имя объекта без пробельных символов по краям. */
    public final String name;

    /** Категория объекта, используемая визуализацией и карточкой подробностей. */
    public final Kind kind;

    /**
     * Создаёт идентичность космического объекта.
     *
     * @param name отображаемое имя; после удаления пробелов по краям не должно быть пустым
     * @param kind обязательная категория объекта
     * @throws IllegalArgumentException если имя равно {@code null}, является пустым или состоит
     *                                  только из пробельных символов
     * @throws NullPointerException если {@code kind} равен {@code null}
     */
    public IdentityComponent(String name, Kind kind) {
        if (name == null || name.strip().isEmpty()) {
            throw new IllegalArgumentException("Имя космического объекта не должно быть пустым");
        }
        if (kind == null) {
            throw new NullPointerException("Тип космического объекта не должен быть null");
        }

        this.name = name.strip();
        this.kind = kind;
    }
}
