package com.spacesim.components;
import com.badlogic.ashley.core.Component;
import com.badlogic.ashley.core.Entity;

/**
 * Состояние конечного автомата автономного торгового флота.
 *
 * <p>{@link com.spacesim.systems.TradeAISystem} является владельцем маршрута:
 * он читает и изменяет все оперативные поля, перемещает флот, выполняет сделки
 * и восстанавливает маршрут при изменении рынка. Интерфейс читает состояние,
 * денежный баланс и выбранную цель. Фактический груз хранится только в
 * {@link InventoryComponent}, а не в этом компоненте.</p>
 *
 * <p>Ссылки на станции допустимо хранить как {@code null}, когда маршрут не
 * выбран. Все денежные значения выражены в кредитах, интервалы — в секундах
 * игрового времени, количества — в целых единицах товара.</p>
 */
public class TradeAIComponent implements Component {
    /** Этап выполнения торгового маршрута. */
    public enum State {
        /** Флот не имеет активного перехода и может искать покупателя или продавца. */
        IDLE,

        /** Флот движется к станции, на которой планирует приобрести товар. */
        TRAVEL_TO_BUY,

        /** Флот достиг станции покупки; система должна попытаться выполнить сделку. */
        BUYING,

        /** Флот с грузом движется к станции, покупающей выбранный товар. */
        TRAVEL_TO_SELL,

        /** Флот достиг станции продажи; система должна реализовать доступную часть груза. */
        SELLING
    }

    /**
     * Текущий этап автомата. Значение устанавливает и переключает торговый ИИ;
     * штатное значение никогда не равно {@code null}.
     */
    public State state = State.IDLE;

    /**
     * Станция запланированной покупки или {@code null} для маршрута только на
     * продажу и при отсутствии маршрута.
     */
    public Entity buyStation;

    /** Станция запланированной продажи или {@code null}, если цель не выбрана. */
    public Entity sellStation;

    /**
     * Текущая навигационная цель. Во время маршрута совпадает с
     * {@link #buyStation} либо {@link #sellStation}; вне маршрута равна
     * {@code null}.
     */
    public Entity targetStation;

    /**
     * Идентификатор перевозимого товара; {@code -1} означает отсутствие
     * выбранного товара, иначе ожидается диапазон
     * {@code [0, Constants.MAX_ITEMS)}.
     */
    public int targetItem = -1;

    /**
     * Планируемое к покупке или продаже количество, в целых единицах.
     * При активном маршруте значение положительно, вне маршрута равно нулю.
     */
    public int targetAmount = 0;

    /**
     * Лимит груза, который торговый ИИ разрешает флоту перевозить, в целых
     * единицах. Он применяется совместно с
     * {@link InventoryComponent#capacity}; штатное значение неотрицательно.
     */
    public int cargoSpace = 100;

    /**
     * Денежный баланс флота в кредитах. Торговая система ожидает конечное
     * неотрицательное значение и меняет его только после успешной сделки.
     */
    public float credits = 1000f;

    /**
     * Оценка денежного результата выбранного маршрута в кредитах.
     * Используется для сравнения кандидатов и сбрасывается вместе с маршрутом.
     */
    public float expectedProfit = 0f;

    /**
     * Оставшееся время до повторного поиска маршрута, в секундах.
     * Торговый ИИ уменьшает значение в состоянии {@link State#IDLE}; ноль
     * разрешает немедленный поиск.
     */
    public float routeSearchCooldown = 0f;

    /**
     * Создаёт свободный флот без маршрута: состояние {@link State#IDLE}, лимит
     * груза {@code 100}, баланс {@code 1000} кредитов и нулевой таймер поиска.
     */
    public TradeAIComponent() {
    }

    /**
     * Очищает выбранные станции, товар, количество и оценку результата.
     *
     * <p>Метод намеренно не меняет {@link #state}, {@link #credits},
     * {@link #cargoSpace}, {@link #routeSearchCooldown} и фактический склад
     * флота. Вызывающая система отдельно выбирает следующее состояние автомата
     * и политику повторного поиска.</p>
     */
    public void resetRoute() {
        buyStation = null;
        sellStation = null;
        targetStation = null;
        targetItem = -1;
        targetAmount = 0;
        expectedProfit = 0f;
    }
}
