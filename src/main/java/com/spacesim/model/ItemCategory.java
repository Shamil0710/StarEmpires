package com.spacesim.model;

/**
 * Категория физического хранения и перевозки товара.
 *
 * <p>Категория не заменяет конкретный {@link ItemType}: она объединяет товары с одинаковыми
 * требованиями к грузовому отсеку. Торговые корабли используют её при выборе допустимого груза,
 * тогда как рынки, рецепты и инвентари по-прежнему адресуют конкретные товары числовыми
 * идентификаторами.</p>
 */
public enum ItemCategory {
    /** Твёрдые сырьевые и конструкционные материалы, например руда и сталь. */
    MATERIAL("Материалы"),

    /** Газообразные, жидкие и хранимые в герметичных резервуарах энергоносители. */
    GAS_LIQUID("Газы и жидкости"),

    /** Изготовленная продукция, перевозимая в универсальных контейнерах. */
    FINISHED_GOODS("Готовые товары");

    private final String displayName;

    ItemCategory(String displayName) {
        this.displayName = displayName;
    }

    /**
     * Возвращает русское имя категории для интерфейса и диагностических сообщений.
     *
     * @return непустое неизменяемое имя категории
     */
    public String getDisplayName() {
        return displayName;
    }
}
