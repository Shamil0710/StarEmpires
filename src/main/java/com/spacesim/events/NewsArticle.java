package com.spacesim.events;

import com.badlogic.gdx.graphics.Color;

/**
 * Изменяемый объект данных для новости об экономическом событии.
 *
 * <p>Класс намеренно не выполняет валидацию и не создаёт защитные копии: заголовок, содержимое и
 * цвет могут быть равны {@code null}, а ссылка на {@link Color} сохраняется непосредственно.
 * Получатель статьи может редактировать все поля. Экземпляр не является потокобезопасным; при
 * передаче между потоками вызывающий код должен обеспечить безопасную публикацию и синхронизацию.</p>
 */
public class NewsArticle {
    /**
     * Краткий заголовок новости; может быть равен {@code null}.
     */
    public String headline;

    /**
     * Развёрнутый текст новости; может быть равен {@code null}.
     */
    public String content;

    /**
     * Предпочтительный цвет отображения или {@code null} для цвета по умолчанию.
     *
     * <p>Объект цвета не копируется, поэтому его последующая мутация видна через это поле.</p>
     */
    public Color color;

    /**
     * Время создания статьи в миллисекундах эпохи Unix.
     *
     * <p>Начальное значение берётся из {@link System#currentTimeMillis()} и не гарантирует ни
     * монотонность, ни уникальность. Поле остаётся изменяемым.</p>
     */
    public long timestamp;

    /**
     * Создаёт новостную статью и фиксирует текущее системное время.
     *
     * @param h заголовок; допускается {@code null}
     * @param c содержимое; допускается {@code null}
     * @param col цвет отображения; допускается {@code null} и сохраняется без копирования
     */
    public NewsArticle(String h, String c, Color col) {
        this.headline = h; this.content = c; this.color = col;
        this.timestamp = System.currentTimeMillis();
    }
}
