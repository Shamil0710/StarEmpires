package com.spacesim.util;

import com.badlogic.ashley.core.Entity;
import com.badlogic.gdx.math.Vector2;
import com.badlogic.gdx.utils.LongMap;
import com.spacesim.constants.Constants;
import java.util.ArrayList;
import java.util.List;

/**
 * Изменяемый пространственный индекс сущностей на основе равномерной хеш-сетки.
 *
 * <p>Мировая плоскость разбивается на квадратные ячейки со стороной
 * {@link Constants#CELL_SIZE}. Координаты ячейки вычисляются через округление вниз, поэтому
 * отрицательные мировые координаты распределяются симметрично ожидаемым диапазонам: например,
 * небольшое отрицательное значение попадает в ячейку {@code -1}, а не в {@code 0}. Пара целых
 * координат без потерь упаковывается в один ключ {@code long}. Поддерживаемые
 * мировые координаты должны после деления на размер ячейки помещаться в
 * {@code int}; более крупные конечные значения насыщаются при приведении и
 * схлопываются в крайнюю ячейку.</p>
 *
 * <p>Индекс предназначен для полного перестроения: обычно в начале кадра вызывается
 * {@link #clear()}, после чего актуальные сущности заново добавляются через {@link #insert(Entity,
 * Vector2)}. Повторная вставка одной сущности не подавляется и приводит к повтору в результатах.
 * Запрос соседей является только широкофазным: он объединяет квадратный набор ячеек и не проверяет
 * фактическое евклидово расстояние до сущностей.</p>
 *
 * <p>Класс не является потокобезопасным. Вставка, очистка и чтение не должны выполняться параллельно
 * без внешней синхронизации. Ссылки на сущности сохраняются как есть; жизненным циклом самих
 * сущностей сетка не управляет.</p>
 */
public class SpatialHashGrid {
    private final LongMap<List<Entity>> grid = new LongMap<>();

    /**
     * Создаёт пустую сетку с глобальным размером ячейки {@link Constants#CELL_SIZE}.
     */
    public SpatialHashGrid() {
    }

    /**
     * Создаёт пустую сетку, сохраняя совместимость со старым конструктором.
     *
     * <p>Переданное значение намеренно игнорируется: фактический размер ячейки всегда равен
     * {@link Constants#CELL_SIZE}. В том числе метод не проверяет знак или величину аргумента.</p>
     *
     * @param ignoredCellSize неиспользуемое значение размера ячейки
     */
    public SpatialHashGrid(int ignoredCellSize) {
        // Размер ячейки задаётся глобально через Constants.CELL_SIZE.
    }

    /**
     * Добавляет ссылку на сущность в ячейку указанной позиции.
     *
     * <p>Сохраняются только вычисленный ключ ячейки и ссылка на сущность; сам вектор позиции не
     * удерживается. Метод не проверяет повторную вставку и не запрещает {@code null} вместо сущности,
     * поэтому ответственность за эти инварианты лежит на вызывающем коде. Координаты позиции
     * предполагаются конечными и ограниченными диапазоном координат ячейки {@code int}, хотя
     * отдельная проверка этих условий не выполняется.</p>
     *
     * @param entity индексируемая сущность; ссылка сохраняется без копирования и проверки
     * @param pos текущая мировая позиция сущности
     * @throws NullPointerException если позиция равна {@code null}
     */
    public void insert(Entity entity, Vector2 pos) {
        long key = getKey(pos.x, pos.y);
        List<Entity> cell = grid.get(key);
        if (cell == null) {
            cell = new ArrayList<>();
            grid.put(key, cell);
        }
        cell.add(entity);
    }

    /**
     * Возвращает сущности из ячейки позиции и соседних ячеек в заданном радиусе.
     *
     * <p>При радиусе {@code r} просматривается квадрат размером
     * {@code (2 * r + 1) x (2 * r + 1)} ячеек. Точное расстояние до {@code pos} не вычисляется.
     * Результат представляет собой новый изменяемый список, изменение которого не влияет на сетку;
     * сами ссылки на сущности не копируются. Порядок элементов определяется обходом ячеек и порядком
     * вставки, а повторно индексированная сущность может встретиться несколько раз.</p>
     *
     * <p>Поддерживаемый контракт предполагает небольшой неотрицательный {@code radiusCells}, а также
     * координаты ячеек, для которых прибавление этого радиуса не переполняет {@code int}.
     * Отрицательные значения не проверяются и не имеют гарантированной семантики. Очень большие
     * значения имеют квадратичную стоимость, а {@link Integer#MAX_VALUE} способен привести к
     * переполнению счётчика цикла; такие аргументы использовать нельзя.</p>
     *
     * @param pos центр поиска в мировых координатах
     * @param radiusCells неотрицательное число дополнительных ячеек в каждом направлении
     * @return новый изменяемый список ссылок из просмотренных ячеек
     * @throws NullPointerException если позиция равна {@code null}
     */
    public List<Entity> getNearby(Vector2 pos, int radiusCells) {
        List<Entity> result = new ArrayList<>();
        int cx = getCellCoordinate(pos.x);
        int cy = getCellCoordinate(pos.y);

        for (int x = -radiusCells; x <= radiusCells; x++) {
            for (int y = -radiusCells; y <= radiusCells; y++) {
                long key = getHashKey(cx + x, cy + y);
                List<Entity> cell = grid.get(key);
                if (cell != null) result.addAll(cell);
            }
        }
        return result;
    }

    /**
     * Удаляет из индекса все ячейки и ссылки на сущности.
     *
     * <p>Сами сущности Ashley не удаляются и не изменяются.</p>
     */
    public void clear() { grid.clear(); }

    private long getKey(float x, float y) {
        return getHashKey(getCellCoordinate(x), getCellCoordinate(y));
    }

    private int getCellCoordinate(float value) {
        return (int)Math.floor(value / Constants.CELL_SIZE);
    }

    private long getHashKey(int x, int y) {
        return ((long)x << 32) | ((long)y & 0xFFFFFFFFL);
    }
}
