package com.spacesim.world;

/** Классифицирует доминирующую физическую причину локального экономического bottleneck. */
public enum EconomicBottleneckType {
    /** Спрос превышает доступное предложение при отсутствующей или недостаточной производственной мощности. */
    PRODUCTION_CAPACITY_SHORTAGE,
    /** Производители существуют, но не могут работать из-за отсутствующих физических входных ресурсов. */
    LOGISTICS_SHORTAGE,
    /** Производители существуют, но recipe не помещается в текущую складскую ёмкость. */
    STORAGE_CONGESTION
}
